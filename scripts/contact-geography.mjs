/**
 * Regenerates the single versioned contact-geography registry consumed by
 * Flutter and the Gateway. `--iso-source PATH` refreshes from a pinned
 * Debian iso-codes checkout; otherwise the committed snapshot is authoritative.
 * `--check` never writes, and is suitable for CI.
 */
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {createRequire} from 'node:module';
import {readFileSync, writeFileSync} from 'node:fs';
import {resolve} from 'node:path';

const root=resolve(import.meta.dirname,'..');
const {getCountryCallingCode}=createRequire(resolve(root,'services/gateway/package.json'))('libphonenumber-js/max');
const source=resolve(root,'data/contact-geography.v1.json');
const mobile=resolve(root,'apps/mobile/assets/contact_geography.json');
const dart=resolve(root,'apps/mobile/lib/src/core/phone/country_contact_generated.dart');
const gateway=resolve(root,'services/gateway/src/country_contact_generated.ts');
const codes='NG GH KE ZA UG TZ RW CM SN CI BJ BF ML NE GN SL LR GM TD TG CG CD ET EG MA DZ TN US CA GB IE FR DE ES IT NL IN PK BD CN AE SA QA AU BR'.split(' ');
const aliases={CI:'Côte d’Ivoire',CD:'DR Congo',CG:'Congo',GB:'United Kingdom',AE:'United Arab Emirates'};
const hash=(value)=>createHash('sha256').update(value).digest('hex');
const args=process.argv.slice(2);
const sourceIndex=args.indexOf('--iso-source');
const check=args.includes('--check');
if(check&&sourceIndex!==-1)throw new Error('--check and --iso-source cannot be combined');
let registry;
if(sourceIndex!==-1){
  if(!args[sourceIndex+1])throw new Error('Expected --iso-source PATH');
  const dir=resolve(args[sourceIndex+1]);
  const upstreamCommit=execFileSync('git',['-C',dir,'rev-parse','--short=7','HEAD'],
    {encoding:'utf8'}).trim();
  if(upstreamCommit!=='0ca8260')throw new Error('Review and update pinned ISO version/commit before refreshing');
  const countryBytes=readFileSync(resolve(dir,'data/iso_3166-1.json'));
  const subdivisionBytes=readFileSync(resolve(dir,'data/iso_3166-2.json'));
  const countries=JSON.parse(countryBytes)['3166-1'];
  const subdivisions=JSON.parse(subdivisionBytes)['3166-2'];
  registry={
    version:'iso-codes-4.20.1-libphonenumber-js-1.13.15-v1',
    source:{project:'Debian iso-codes',repository:'https://salsa.debian.org/debian/iso-codes',
      commit:'0ca8260',iso3166_1_sha256:hash(countryBytes),iso3166_2_sha256:hash(subdivisionBytes),
      phoneMetadata:'libphonenumber-js/max@1.13.15'},
    countries:codes.map(iso=>{
      const row=countries.find(item=>item.alpha_2===iso);
      if(!row)throw new Error(`No ISO 3166-1 country ${iso}`);
      const divisions=subdivisions.filter(item=>item.code.startsWith(`${iso}-`))
        .map(item=>({code:item.code,name:item.name})).sort((a,b)=>a.name.localeCompare(b.name));
      return {iso,name:aliases[iso]??row.name,dialCode:getCountryCallingCode(iso),subdivisions:divisions};
    }),
  };
}else registry=JSON.parse(readFileSync(source,'utf8'));
if(!Array.isArray(registry.countries)||registry.countries.length!==codes.length||
  registry.countries.some((country,i)=>country.iso!==codes[i]||
    !/^\d{1,3}$/.test(country.dialCode)||
    country.dialCode!==getCountryCallingCode(country.iso)||
    country.subdivisions.some(s=>!s.code.startsWith(`${country.iso}-`)))){
  throw new Error('Invalid contact-geography snapshot or calling-code mismatch');
}
const snapshot=JSON.stringify(registry,null,2)+'\n';
const asset=JSON.stringify(registry)+'\n';
const flags=(iso)=>[...iso].map(c=>String.fromCodePoint(c.charCodeAt(0)-65+0x1f1e6)).join('');
const dartText=`// GENERATED by scripts/contact-geography.mjs. Do not hand edit.\npart of 'country_codes.dart';\n\nconst String kContactGeographyVersion = ${JSON.stringify(registry.version)};\nconst List<PhoneCountry> kPhoneCountries = [\n`+
  registry.countries.map(c=>`  PhoneCountry(dialCode: ${JSON.stringify(c.dialCode)}, iso: ${JSON.stringify(c.iso)}, name: ${JSON.stringify(c.name)}, flag: ${JSON.stringify(flags(c.iso))}),`).join('\n')+
  '\n];\n';
const rows=Object.fromEntries(registry.countries.map(c=>[c.iso,{dialCode:c.dialCode,subdivisions:c.subdivisions.map(s=>s.code)}]));
const tsText=`// GENERATED by scripts/contact-geography.mjs. Do not hand edit.\nexport const contactGeographyVersion = ${JSON.stringify(registry.version)};\nexport const contactCountries:Readonly<Record<string,Readonly<{dialCode:string;subdivisions:readonly string[]}>>> = ${JSON.stringify(rows,null,2)};\n`;
for(const [path,content] of [[source,snapshot],[mobile,asset],[dart,dartText],[gateway,tsText]]){
  if(check){if(readFileSync(path,'utf8')!==content)throw new Error(`Outdated generated geography: ${path}`);}
  else writeFileSync(path,content);
}
process.stdout.write(`${check?'Verified':'Generated'} ${registry.version}: ${registry.countries.length} countries\n`);
