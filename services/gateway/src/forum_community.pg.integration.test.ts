import Fastify from 'fastify';
import {randomUUID} from 'node:crypto';
import {afterAll,beforeAll,describe,expect,it} from 'vitest';
import {createCanonicalId} from '@masanawa/contracts';
import {createPostgresPool,runMigrations,platformProductMigrationRoots,type Pool} from '@masanawa/postgres';
import {registerCitizenForum} from './citizen_forum_routes.js';

const url=process.env.MASANAWA_TEST_DATABASE_URL;
describe.skipIf(!url)('Forum community tools in PostgreSQL',()=>{
 const tenant=createCanonicalId('tenant'),other=createCanonicalId('tenant');
 const members=Array.from({length:6},()=>createCanonicalId('user')),outsider=createCanonicalId('user');
 const topic=randomUUID(),hidden=randomUUID(),poll=randomUUID();
 let pool:Pool;let app:ReturnType<typeof Fastify>;
 beforeAll(async()=>{
  pool=createPostgresPool({connectionString:url!,applicationName:'forum-community-integration'});
  await runMigrations(pool,platformProductMigrationRoots());
  for(const t of [tenant,other])await pool.query('INSERT INTO identity.tenants(tenant_id,created_at,updated_at) VALUES($1,now(),now())',[t]);
  for(const [t,u] of [...members.map(u=>[tenant,u]),[other,outsider]])await pool.query('INSERT INTO identity.users(tenant_id,user_id,created_at,updated_at) VALUES($1,$2,now(),now())',[t,u]);
  for(const [id,state] of [[topic,'published'],[hidden,'hidden']])await pool.query("INSERT INTO agents.forum_topics(tenant_id,id,user_id,room,title,body,kind,jurisdiction,state) VALUES($1,$2,$3,'cac',$4,'A synthetic complaint about a public registration process.','complaint','National',$5)",[tenant,id,members[0],id===topic?'Registration service complaint':'Hidden registration complaint',state]);
  for(const id of [topic,hidden])await pool.query('INSERT INTO agents.forum_topic_pins(tenant_id,topic_id,room,pinned_by) VALUES($1,$2,$3,$4)',[tenant,id,'cac','fixture']);
  await pool.query("INSERT INTO agents.forum_polls(tenant_id,id,topic_id,question,options,closes_at,created_by) VALUES($1,$2,$3,'Which service needs improvement?',ARRAY['Processing','Support'],now()+interval '1 day','fixture')",[tenant,poll,topic]);
  await pool.query("INSERT INTO agents.forum_complaint_progress(tenant_id,topic_id,status,updated_by) VALUES($1,$2,'in_progress','fixture')",[tenant,topic]);
  app=Fastify({logger:false});
  registerCitizenForum(app,{pool,publicTenantId:tenant,authorize:async header=>{const user=header?.slice(7);if(user===outsider)return {tenantId:other,userId:outsider};if(!user||!members.includes(user))throw Object.assign(new Error('unauthorized'),{statusCode:401});return {tenantId:tenant,userId:user}},beforeWrite:async()=>{}});
  await app.ready();
 },120000);
 afterAll(async()=>{await app?.close();await pool?.end()});
 const get=(path:string,user?:string)=>app.inject({url:'/v1/forum/'+path,headers:user?{authorization:'Bearer '+user}:{}});
 const post=(path:string,payload:object,user?:string)=>app.inject({method:'POST',url:'/v1/forum/community/'+path,payload,headers:user?{authorization:'Bearer '+user}:{}});
 it('scopes public content, private bookmarks and one current vote per account; suppresses low samples and rejects closed votes',async()=>{
  const first=await get('community?room=cac');expect(first.statusCode).toBe(200);
  expect(first.json().pinned.map((p:{id:string})=>p.id)).toEqual([topic]);
  expect(first.json().complaints).toEqual([expect.objectContaining({id:topic,status:'in_progress'})]);
  expect(first.json().polls).toEqual([expect.objectContaining({id:poll,total:null,counts:null})]);
  expect((await get('community?room=rights')).json().polls).toEqual([]);
  expect((await get('community/mine')).statusCode).toBe(401);
  expect((await get('community/mine',outsider)).statusCode).toBe(403);
  expect((await post('bookmark',{articleId:'arrest',enabled:true},members[0])).statusCode).toBe(200);
  expect((await post('bookmark',{articleId:'arrest',enabled:true},members[0])).statusCode).toBe(200);
  expect((await get('community/mine',members[0])).json().bookmarks).toEqual(['arrest']);
  expect((await get('community/mine',members[1])).json().bookmarks).toEqual([]);
  expect((await post('vote',{pollId:poll,choice:2},members[0])).statusCode).toBe(400);
  for(const u of members.slice(0,4))expect((await post('vote',{pollId:poll,choice:0},u)).statusCode).toBe(200);
  expect((await get('community')).json().polls[0].total).toBeNull();
  expect((await post('vote',{pollId:poll,choice:1},members[4])).statusCode).toBe(200);
  expect((await get('community')).json().polls[0]).toMatchObject({total:5,counts:[4,1]});
  expect((await post('vote',{pollId:poll,choice:1},members[0])).statusCode).toBe(200);
  expect((await get('community')).json().polls[0]).toMatchObject({total:5,counts:[3,2]});
  expect((await get('community/mine',members[0])).json().votes).toEqual([{poll_id:poll,choice:1}]);
  expect((await get('community/mine',members[5])).json().votes).toEqual([]);
  expect((await post('bookmark',{articleId:'arrest',enabled:false},members[0])).statusCode).toBe(200);
  expect((await get('community/mine',members[0])).json().bookmarks).toEqual([]);
  await pool.query('UPDATE agents.forum_polls SET closed=true WHERE tenant_id=$1 AND id=$2',[tenant,poll]);
  expect((await post('vote',{pollId:poll,choice:0},members[0])).statusCode).toBe(409);
  await pool.query("UPDATE agents.forum_topics SET state='hidden' WHERE tenant_id=$1 AND id=$2",[tenant,topic]);
  const last=(await get('community')).json();expect(last.pinned).toEqual([]);expect(last.polls).toEqual([]);expect(last.complaints).toEqual([]);
  expect((await get('community/mine',members[0])).json().votes).toEqual([]);
 },30000);
});
